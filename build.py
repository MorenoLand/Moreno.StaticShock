#!/usr/bin/env python3
"""Build the lifted program.

Generates runtime/project.h from project.toml, collects src/ and runtime/, compiles every C file
with the 32-bit MinGW compiler, and links the host with the guest/tail/text section layout.
"""
import argparse
import hashlib
import os
import shutil
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT / "pipeline"))
import cfg


def quote(text):
    return '"' + str(text).replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_project_header():
    original = Path(cfg.PROJECT.get("exe", "target.exe")).name
    text = """/* project.h: generated by build.py from project.toml. Do not edit by hand. */
#ifndef SS_PROJECT_H
#define SS_PROJECT_H

#define SS_PROJECT       %s
#define SS_HOST_NAME     %s
#define SS_HOST_EXE      %s
#define SS_ORIGINAL_EXE  %s
#define SS_OEP           0x%xu
#define SS_IMAGE_BASE    0x%xu
#define SS_IMAGE_END     0x%xu
#define SS_CODE_LO       0x%xu
#define SS_CODE_HI       0x%xu
#define SS_GUEST_SIZE    0x%xu
#define SS_TAIL_SIZE     0x%xu
#define SS_DATA_SIZE     (SS_IMAGE_END - SS_IMAGE_BASE)
#define SS_MAP_SIZE      SS_GUEST_SIZE
#define SS_TAIL_MAP_SIZE (SS_TAIL_SIZE + 0x1000u)
#define SS_TEXT_SECTION  (SS_IMAGE_BASE + 0x1000u + SS_GUEST_SIZE + SS_TAIL_SIZE)

#endif
""" % (quote(cfg.NAME), quote(cfg.HOST_NAME), quote(cfg.HOST_EXE), quote(original),
       cfg.OEP, cfg.IMAGE_BASE, cfg.IMAGE_END, cfg.CODE_LO, cfg.CODE_HI,
       cfg.GUEST_SIZE, cfg.TAIL_SIZE)
    (ROOT / "runtime" / "project.h").write_text(text, encoding="utf-8")


def ensure_api():
    api_c = ROOT / "runtime" / "api_gen.c"
    table = ROOT / "recomp" / "data" / "api_table.json"
    if api_c.exists():
        return
    if not table.exists():
        sys.exit("runtime/api_gen.c is missing and recomp/data/api_table.json does not exist.\n"
                 "  run: python pipeline/make_api.py && python pipeline/gen_api.py")
    subprocess.run([sys.executable, str(ROOT / "pipeline" / "gen_api.py")], check=True)


def sources(include_driver=False):
    files = sorted((ROOT / "src").rglob("*.c"))
    files += sorted((ROOT / "runtime").glob("*.c"))
    if include_driver:
        files = [f for f in files if f.name not in ("boot.c", "preentry.c", "guest_pad.c")]
    else:
        files = [f for f in files if f.name != "driver.c"]
    return files


def write_image_blob():
    blob = ROOT / "src" / "image.bin"
    if not blob.exists():
        sys.exit("src/image.bin is missing; run: python static_shock.py lift")
    src = ROOT / "build" / "image_blob.c"
    path = str(blob).replace("\\", "/").replace('"', '\\"')
    text = ('__asm__(\n'
            '".section .rodata\\n"\n'
            '".global _rt_image_blob\\n"\n'
            '".balign 16\\n"\n'
            '"_rt_image_blob:\\n"\n'
            '".incbin \\"' + path + '\\"\\n");\n')
    if not src.exists() or src.read_text(encoding="utf-8") != text:
        src.write_text(text, encoding="utf-8")
    return src


def windres_exe():
    windres = next((p for p in (Path(cfg.mingw32()) / "bin" / "i686-w64-mingw32-windres.exe",
                                Path(cfg.mingw32()) / "bin" / "windres.exe") if p.is_file()), None)
    if windres is None:
        found = shutil.which("i686-w64-mingw32-windres") or shutil.which("windres")
        windres = Path(found) if found else None
    return windres


def mingw_path():
    p = str(Path(cfg.mingw32()) / "bin")
    if p not in os.environ.get("PATH", "").split(os.pathsep):
        os.environ["PATH"] = p + os.pathsep + os.environ.get("PATH", "")


def build_resources():
    value = cfg.BUILD_CFG.get("resources", "")
    if value:
        res = Path(value)
        if not res.is_absolute():
            res = ROOT / res
    else:
        found = sorted((ROOT / "recomp" / "data").glob("*.res"))
        res = found[0] if found else None
    if res is None:
        return []
    if not res.exists():
        sys.exit("resources file not found: %s" % res)
    windres = windres_exe()
    if windres is None:
        print("warning: windres not found; original resources are not linked", file=sys.stderr)
        return []
    out = ROOT / "build" / "resources.o"
    args = [str(windres), "-i", str(res), "-J", "res", "-O", "coff"]
    if "i686" not in windres.name:
        args.append("--target=pe-i386")
    subprocess.run(args + ["-o", str(out)], check=True)
    return [out]


def build_icon():
    icon = cfg.ICON
    rc = ROOT / "build" / "host.rc"
    lines = ['1 24 "host.manifest"']
    if icon:
        p = Path(icon)
        if not p.is_absolute():
            p = ROOT / p
        lines.append('1 ICON "%s"' % str(p).replace("\\", "\\\\"))
    rc.write_text("\n".join(lines) + "\n", encoding="utf-8")
    windres = windres_exe()
    out = ROOT / "build" / "host.res.o"
    if windres:
        args = [str(windres), "-I", str(ROOT / "runtime")]
        if "i686" not in windres.name:
            args.append("--target=pe-i386")
        subprocess.run(args + [str(rc), str(out)], check=True)
        return out
    print("warning: windres not found; building without an icon/manifest", file=sys.stderr)
    return None


def header_digest():
    h = hashlib.sha256()
    for base in (ROOT / "runtime", ROOT / "src", ROOT / "recomp" / "data"):
        if not base.exists():
            continue
        for p in sorted(base.rglob("*.h")):
            h.update(str(p.relative_to(ROOT)).encode("utf-8"))
            h.update(p.read_bytes())
    return h.hexdigest()


def compile_one(cc, cflags, src, hdr):
    rel = src.relative_to(ROOT)
    obj = ROOT / "build" / "obj" / (str(rel).replace("\\", "_").replace("/", "_") + ".o")
    obj.parent.mkdir(parents=True, exist_ok=True)
    key = hashlib.sha256(src.read_bytes() + hdr.encode("utf-8") + " ".join(cflags).encode("utf-8")).hexdigest()
    stamp = obj.with_suffix(obj.suffix + ".sha")
    if obj.exists() and stamp.exists() and stamp.read_text(encoding="utf-8") == key:
        return src, obj, 0, ""
    r = subprocess.run([str(cc)] + cflags + [str(src), "-o", str(obj)], capture_output=True, text=True)
    if r.returncode == 0:
        stamp.write_text(key, encoding="utf-8")
    return src, obj, r.returncode, r.stdout + r.stderr


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--driver", action="store_true", help="build the differential driver instead of the client")
    ap.add_argument("--jobs", type=int, default=int(os.environ.get("SS_JOBS", os.cpu_count() or 1)))
    args = ap.parse_args()

    if cfg.ARCH != "x86":
        sys.exit("arch = %r: PE32+ parsing and configuration are available, but the x64 lifter, "
                 "runtime ABI and build layout are WIP. The shipped backend is x86-32." % cfg.ARCH)

    mingw = Path(cfg.mingw32())
    cc = mingw / "bin" / "i686-w64-mingw32-gcc.exe"
    if not cc.exists():
        cc = Path(shutil.which("i686-w64-mingw32-gcc") or "")
    if not cc.exists():
        sys.exit("i686-w64-mingw32-gcc not found; set build.mingw32 in project.toml")

    mingw_path()
    write_project_header()
    blob = write_image_blob()
    ensure_api()

    objects = []
    obj_dir = ROOT / "build" / "obj"
    obj_dir.mkdir(parents=True, exist_ok=True)
    cflags = ["-c", "-fno-strict-aliasing"] + cfg.cflags() + [
        "-I" + str(ROOT / "runtime"), "-I" + str(ROOT / "src"),
        "-I" + str(ROOT / "recomp" / "data")]
    files = sources(args.driver) + [blob]
    hdr = header_digest()
    with ThreadPoolExecutor(max_workers=max(1, args.jobs)) as pool:
        for src, obj, code, output in pool.map(lambda f: compile_one(cc, cflags, f, hdr), files):
            if code:
                print(output[:4000])
                sys.exit("compile failed: %s" % src)
            objects.append(obj)

    res = build_icon()
    if res:
        objects.append(res)
    objects += build_resources()

    base = cfg.IMAGE_BASE
    guest = base + 0x1000
    tail = guest + cfg.GUEST_SIZE
    text = (tail + cfg.TAIL_SIZE + 0xFFF) & ~0xFFF
    host = ROOT / "bin" / ("recomp.exe" if args.driver else cfg.HOST_EXE)
    host.parent.mkdir(parents=True, exist_ok=True)
    rsp = ROOT / "build" / "objects.rsp"
    rsp.write_text("\n".join(quote(o) for o in objects) + "\n", encoding="utf-8")

    link = [str(cc), "-o", str(host), "@" + str(rsp), "-static-libgcc", "-mconsole"]
    if args.driver:
        link += ["-Wl,--stack,0x%x" % int(cfg.BUILD_CFG.get("stack", 0x10000000))]
    else:
        link += ["-Wl,--image-base,0x%x" % base,
                 "-Wl,--section-start=.guest=0x%x" % guest,
                 "-Wl,--section-start=.tail=0x%x" % tail,
                 "-Wl,--section-start=.text=0x%x" % text,
                 "-Wl,--disable-reloc-section", "-Wl,--disable-dynamicbase",
                 "-Wl,--large-address-aware", "-Wl,-e,rt_preentry",
                 "-Wl,--stack,0x%x" % int(cfg.BUILD_CFG.get("stack", 0x10000000)),
                 "-Wl,--heap,0x%x" % int(cfg.BUILD_CFG.get("heap", 0x10000000)),
                 "-Wl,-Map," + str(ROOT / "bin" / "lift.map")]
    link += ["-l" + lib for lib in cfg.host_libs()]

    r = subprocess.run(link)
    if r.returncode or not host.exists():
        sys.exit("link failed: %s" % host)
    print("built %s" % host)


if __name__ == "__main__":
    main()

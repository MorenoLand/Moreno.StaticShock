# gen_api.py: turn recomp/data/api_table.json into runtime/api_gen.c.
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import cfg

api = json.load(open(os.path.join(cfg.DATA, "api_table.json"), encoding="utf-8"))
names = {}
for e in api:
    if e.get("nargs") is not None:
        names[e["name"]] = e["nargs"]

# Optional second table (OpenGL or another runtime-loaded API).
extra = os.path.join(cfg.DATA, "gl_table.json")
if os.path.exists(extra):
    gl = json.load(open(extra, encoding="utf-8"))
    for e in gl.get("core", []) + gl.get("extensions", []):
        if e.get("nargs") is not None:
            names.setdefault(e["name"], e["nargs"])

with open(os.path.join(cfg.RT, "api_gen.c"), "w", encoding="utf-8") as o:
    o.write('/* generated by gen_api.py: do not edit */\n#include "api.h"\n\nconst ApiStatic api_static[] = {\n')
    for e in api:
        o.write('    {0x%s, "%s", "%s", %s, %d},\n' % (
            e["ea"].replace("0x", ""), e["module"], e["name"],
            e["nargs"] if e.get("nargs") is not None else -1,
            1 if e.get("conv") == "cdecl" else 0))
    o.write("};\nconst int api_static_n = %d;\n\nconst NameArgs name_args[] = {\n" % len(api))
    for k in sorted(names):
        o.write('    {"%s", %d},\n' % (k, names[k]))
    o.write("};\nconst int name_args_n = %d;\n" % len(names))
print("api entries %d, names %d" % (len(api), len(names)))

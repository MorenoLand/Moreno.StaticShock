#!/usr/bin/env python3
"""Build the WebAssembly target.

The lifted C and the image data are shared with the native build. The wasm module reserves the
guest address range below GLOBAL_BASE and links the runtime/wasm host layer in place of the Win32
host.
"""
import argparse
import os
import shutil
import subprocess
import sys
import time
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT / "pipeline"))
import cfg
import build as native

GLOBAL_BASE = cfg.wasm_global_base()
INITIAL_MEMORY = cfg.wasm_initial_memory()
STACK_SIZE = cfg.wasm_stack_size()
GUEST_STACK = cfg.wasm_guest_stack()
OBJ = ROOT / "build" / "wasm_obj"
GEN = ROOT / "build" / "wasm"
WEB = ROOT / "build" / "wasm_web"
OUT = ROOT / "bin" / "wasm"


def quote(text):
    return '"' + str(text).replace("\\", "\\\\").replace('"', '\\"') + '"'


def emcc_path(flag=""):
    for value in (flag, os.environ.get("SS_EMCC"), cfg.wasm_emcc()):
        if value:
            p = Path(value)
            return p if p.exists() else Path(shutil.which(value) or value)
    local = ROOT / "build" / "emsdk" / "upstream" / "emscripten" / "emcc.exe"
    if local.exists():
        return local
    found = shutil.which("emcc")
    if found:
        return Path(found)
    sys.exit("emcc not found; set [wasm].emcc, SS_EMCC, --emcc, or install emsdk under build/emsdk")


def write_headers():
    native.write_project_header()
    GEN.mkdir(parents=True, exist_ok=True)
    text = """/* wasm_config.h: generated by build_wasm.py. Do not edit by hand. */
#ifndef WASM_CONFIG_H
#define WASM_CONFIG_H

#define WASM_IMAGE_BASE   0x%xu
#define WASM_IMAGE_END    0x%xu
#define WASM_GLOBAL_BASE  0x%xu
#define WASM_OEP          0x%xu
#define WASM_GUEST_STACK  0x%xu
#define WASM_ORIGINAL_EXE %s

#endif
""" % (cfg.IMAGE_BASE, cfg.IMAGE_END, GLOBAL_BASE, cfg.OEP, GUEST_STACK,
       quote(Path(cfg.PROJECT.get("exe", "target.exe")).name))
    path = GEN / "wasm_config.h"
    if not path.exists() or path.read_text(encoding="utf-8") != text:
        path.write_text(text, encoding="utf-8")


def sources():
    files = sorted((ROOT / "src").rglob("*.c"))
    if not files:
        sys.exit("src/ has no lifted C. The wasm host builds the same source as the native target.")
    files += [ROOT / "runtime" / "rt.c", ROOT / "runtime" / "api_gen.c"]
    files += sorted((ROOT / "runtime" / "wasm").glob("*.c"))
    return files


def obj_path(src):
    rel = src.relative_to(ROOT)
    return OBJ / (str(rel).replace("\\", "_").replace("/", "_") + ".o")


def needs_compile(src):
    obj = obj_path(src)
    return not obj.exists() or obj.stat().st_mtime < src.stat().st_mtime


def compile_one(cc, src):
    obj = obj_path(src)
    obj.parent.mkdir(parents=True, exist_ok=True)
    if not needs_compile(src):
        return src, obj, 0, ""
    cmd = [str(cc), "-c", "-O1", "-g", "-w",
           "-I" + str(ROOT / "runtime"),
           "-I" + str(ROOT / "runtime" / "wasm"),
           "-I" + str(GEN),
           "-I" + str(ROOT / "src"),
           "-I" + str(ROOT / "recomp" / "data"),
           str(src), "-o", str(obj)]
    r = subprocess.run(cmd, capture_output=True, text=True)
    return src, obj, r.returncode, r.stdout + r.stderr


def render_shell(data_parts):
    html = (ROOT / "web" / "index.html").read_text(encoding="utf-8")
    values = {
        "{{TITLE}}": cfg.HOST_NAME,
        "{{WIDTH}}": str(cfg.wasm_width()),
        "{{HEIGHT}}": str(cfg.wasm_height()),
        "{{DATA_PARTS}}": str(data_parts),
    }
    for key, value in values.items():
        html = html.replace(key, value)
    (WEB / "index.html").write_text(html, encoding="utf-8")
    shutil.copy2(ROOT / "web" / "web.js", WEB / "web.js")


def publish(data):
    replace_into(WEB, OUT)
    if data:
        step = (data.stat().st_size + cfg.wasm_data_parts() - 1) // cfg.wasm_data_parts()
        for i in range(cfg.wasm_data_parts()):
            blob = data.read_bytes()
            (OUT / ("host.data.part%d" % i)).write_bytes(blob[i * step:(i + 1) * step])
    else:
        for old in OUT.glob("host.data.part*"):
            old.unlink()


def replace_into(src, dst):
    for f in src.iterdir():
        if not f.is_file():
            continue
        for attempt in range(20):
            try:
                os.replace(str(f), str(dst / f.name))
                break
            except OSError:
                if attempt == 19:
                    sys.exit("publish failed: %s" % f.name)
                time.sleep(0.1)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--jobs", type=int, default=max(1, (os.cpu_count() or 2) // 2))
    ap.add_argument("--emcc", default="", help="path to emcc")
    ap.add_argument("--data-dir", default="", help="preload this directory as /data")
    ap.add_argument("--preload-data", action="store_true", help="preload [wasm].data_dir")
    args = ap.parse_args()

    if cfg.ARCH != "x86":
        sys.exit("arch = %r: the wasm backend builds the 32-bit lift; the x64 backend is WIP" % cfg.ARCH)
    if cfg.IMAGE_END > GLOBAL_BASE:
        sys.exit("image end 0x%x is above GLOBAL_BASE 0x%x" % (cfg.IMAGE_END, GLOBAL_BASE))
    if GLOBAL_BASE + 0x4000000 > INITIAL_MEMORY:
        sys.exit("INITIAL_MEMORY 0x%x leaves no room above GLOBAL_BASE 0x%x" % (INITIAL_MEMORY, GLOBAL_BASE))
    image = ROOT / "src" / "image.bin"
    if not image.exists():
        sys.exit("src/image.bin is missing; run: python static_shock.py lift")

    cc = emcc_path(args.emcc)
    files = sources()
    native.ensure_api()
    write_headers()
    WEB.mkdir(parents=True, exist_ok=True)
    OUT.mkdir(parents=True, exist_ok=True)
    OBJ.mkdir(parents=True, exist_ok=True)

    changed = sum(1 for f in files if needs_compile(f))
    print("compiling %d of %d files with %d jobs" % (changed, len(files), args.jobs))
    objects = []
    with ThreadPoolExecutor(max_workers=args.jobs) as pool:
        for src, obj, code, output in pool.map(lambda f: compile_one(cc, f), files):
            if code:
                print("FAILED %s" % src)
                print(output[:4000])
                return 1
            objects.append(obj)

    rsp = ROOT / "build" / "wasm_objects.rsp"
    rsp.write_text("\n".join(quote(o) for o in objects) + "\n", encoding="utf-8")
    cmd = [str(cc), "@" + str(rsp), "-O1", "-g",
           "-sGLOBAL_BASE=%d" % GLOBAL_BASE,
           "-sINITIAL_MEMORY=%d" % INITIAL_MEMORY,
           "-sSTACK_SIZE=%d" % STACK_SIZE,
           "-sALLOW_MEMORY_GROWTH=1",
           "-sASYNCIFY=1",
           "-sASYNCIFY_STACK_SIZE=1048576",
           "-sNO_EXIT_RUNTIME=1",
           "-sFORCE_FILESYSTEM=1",
           "-sENVIRONMENT=web,worker",
           "-sEXPORTED_FUNCTIONS=_main,_wasm_input",
           "--preload-file=%s@/image.bin" % image,
           "-o", str(WEB / "host.js")]
    data_dir = args.data_dir or (cfg.wasm_data_dir() if args.preload_data else "")
    if data_dir:
        p = Path(data_dir)
        if not p.is_absolute():
            p = ROOT / p
        if not p.is_dir():
            sys.exit("data directory not found: %s" % p)
        cmd.append("--preload-file=%s@/data" % p)

    print("linking %s" % (WEB / "host.js"))
    r = subprocess.run(cmd)
    if r.returncode:
        return r.returncode

    data = WEB / "host.data"
    have_data = data.exists()
    render_shell(cfg.wasm_data_parts() if have_data else 0)
    publish(data if have_data else None)
    print("built %s" % (OUT / "host.js"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
